#!/usr/bin/env python3
# W1: the plan oracle test on recaptured C3 rows (test-sparse-attn-plan-oracle --shuffle 7, one log per rows file)
# against C3's own c3_plan logs: per layer, the row statistics c3_plan prints (valid cells per query, ascending rows,
# mean padded G4 union) must be equal, which shows the recapture holds C3's rows; and every memcmp verdict must be
# IDENTICAL.
# usage: compare_c3.py C3_RES_DIR ORACLE_LOG_DIR > summary.md
import sys, re, os
EV, LG = sys.argv[1], sys.argv[2]
files = ['text_f16_p32768', 'text_f16_p131072', 'rand_f16_p32768', 'rand_f16_p131072', 'text_q8_0_p32768', 'text_q8_0_p131072']
pat = re.compile(r'LAYER (\d+) .*valid_per_q=(\S+) sorted_rows=(\S+) union_asc=(\S+)')
tot = match = ident = diff = 0
print('# W1: CPU plan vs the C3 oracle on recaptured C3 rows (generated by compare_c3.py)\n')
print('| rows file | layers | C3 statistics equal | memcmp IDENTICAL | DIFFERENT |')
print('|---|---|---|---|---|')
for f in files:
    ref = {}
    for l in open(os.path.join(EV, f + '_r1.out')):
        m = pat.search(l)
        if l.startswith('LAYER') and m: ref[int(m[1])] = m.groups()[1:]
    mine = {}
    i = d = 0
    for l in open(os.path.join(LG, 'oracle_c3_' + f + '.log')):
        m = pat.search(l)
        if l.startswith('LAYER') and 'shuffle=0' in l and m: mine[int(m[1])] = m.groups()[1:]
        if l.startswith('PLAN_ORACLE'):
            i += 'IDENTICAL' in l; d += 'DIFFERENT' in l
    eq = sum(ref[k] == mine.get(k) for k in ref)
    tot += len(ref); match += eq; ident += i; diff += d
    print('| %s | %d | %d | %d | %d |' % (f, len(ref), eq, i, d))
print('\nC3 statistics equal on %d of %d layers; %d IDENTICAL, %d DIFFERENT -> %s' % (match, tot, ident, diff, 'PASS' if match == tot and diff == 0 and ident > 0 else 'FAIL'))
