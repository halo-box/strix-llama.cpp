#!/usr/bin/env python3
# W1 done-when verdicts from w1_ocon outputs (PLAN-v3 §13 W1):
#   bits     : the CPU op equals bands_ref.h O_CON bit for bit (W1BITS lines), and G = 1 and G = 4 plans give the same bits
#   contract : NMSE(CPU op, O_C18) <= 2.4e-9 (wiki d4k) / 7.3e-8 (SYN 262k); NMSE(CPU op, O_PLAN) <= 1.0e-7 / 3.1e-7
#   cpu FA   : NMSE(CPU FA + src[5], CPU op) <= 3.4e-3 (V = f16); 2.6e-5 (K in {q8_0, q4_0}, V != f16);
#              5.1e-6 (K = bf16, V != f16); 2.3e-7 (K in {f32, f16}, V != f16)
# The bounds are 2 x the p100 of R1-M-Lab A (EV/bands/compact_cpu.md), max over layers. UNI fixtures are reported only.
# usage: analyze_w1.py RESDIR > summary.md
import sys, os, glob, re, collections

D = sys.argv[1]
C18 = {'wiki': 2.4e-9, 'syn': 7.3e-8}
PLAN = {'wiki': 1.0e-7, 'syn': 3.1e-7}

def fa_bound(k, v):
    if v == 'f16':
        return 3.4e-3
    if k in ('q8_0', 'q4_0'):
        return 2.6e-5
    if k == 'bf16':
        return 5.1e-6
    return 2.3e-7

def fixture(tag):
    if tag.startswith('wiki'):
        return 'wiki'
    if tag.startswith('syn'):
        return 'syn'
    return 'uni'

bits = collections.OrderedDict()
nm = collections.OrderedDict()
hashes = []
ok = True
for f in sorted(glob.glob(os.path.join(D, '*.out'))):
    tag = os.path.basename(f)[:-4]
    fx = fixture(tag)
    for ln in open(f):
        p = ln.split()
        if not p:
            continue
        if p[0] == 'W1BITS' and p[1] != 'TOTAL' and len(p) > 3 and p[3] != 'values':
            pair = p[3]; vals = int(p[5]); diff = int(p[7]); geq = int(p[11])
            b = bits.setdefault((fx, tag, pair), [0, 0, 1])
            b[0] += vals; b[1] += diff; b[2] &= geq
        elif p[0] == 'W1B':
            pair, met = p[3], p[4]
            m = re.search(r' nmse (\S+)', ln)
            key = (fx, tag, pair, met)
            nm[key] = max(nm.get(key, 0.0), float(m.group(1)))
        elif p[0] in ('ROWS_HASH',) and p[2] in ('L0', 'L5', 'L11'):
            hashes.append((tag, p[2], p[3], p[5]))

print('# W1: CPU SPARSE_ATTN vs bands_ref.h (generated by analyze_w1.py)\n')
print('## Fixture identity (ROWS_HASH / Q_HASH, fnv1a as bands_cpu.cpp)\n')
for h in hashes:
    print('- %s %s rows %s q %s' % h)

print('\n## Bit equality with bands_ref.h O_CON\n')
print('| fixture run | pairs | values compared | values different | G1 == G4 for every pair |')
print('|---|---|---|---|---|')
runs = collections.OrderedDict()
for (fx, tag, pair), (vals, diff, geq) in bits.items():
    r = runs.setdefault(tag, [0, 0, 0, 1])
    r[0] += 1; r[1] += vals; r[2] += diff; r[3] &= geq
for tag, (npairs, vals, diff, geq) in runs.items():
    print('| %s | %d | %d | %d | %s |' % (tag, npairs, vals, diff, 'yes' if geq else 'NO'))
    ok &= diff == 0 and geq == 1
print()

print('## Contract vs f64 and CPU FA cross-check (max NMSE over layers)\n')
print('| fixture run | pair | CPU op vs O_C18 | bound | CPU op vs O_PLAN | bound | CPU FA vs CPU op | bound | verdict |')
print('|---|---|---|---|---|---|---|---|---|')
pairs = sorted({(fx, tag, pair) for (fx, tag, pair, met) in nm}, key=lambda x: (x[1], x[2]))
for fx, tag, pair in pairs:
    c18 = nm.get((fx, tag, pair, 'cpuop_vs_f64_c18'))
    pl = nm.get((fx, tag, pair, 'cpuop_vs_f64_plan'))
    fa = nm.get((fx, tag, pair, 'cpufa_vs_cpuop'))
    k, v = pair.split('/')
    bfa = fa_bound(k, v)
    if fx in C18:
        good = c18 <= C18[fx] and pl <= PLAN[fx] and fa <= bfa
        ok &= good
        print('| %s | %s | %.3e | %.1e | %.3e | %.1e | %.3e | %.1e | %s |' % (tag, pair, c18, C18[fx], pl, PLAN[fx], fa, bfa, 'PASS' if good else 'FAIL'))
    else:
        print('| %s | %s | %.3e | report | %.3e | report | %.3e | report | report |' % (tag, pair, c18, pl, fa))
print('\nOVERALL %s' % ('PASS' if ok else 'FAIL'))
