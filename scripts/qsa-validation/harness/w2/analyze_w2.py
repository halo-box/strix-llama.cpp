#!/usr/bin/env python3
# W2: summary of the plan harness (w2_plan) outputs and of the same-run C3 reference (c3_plan on the same rows).
# Statistic as C3 (MEASUREMENTS.md C3 "Results (a)"): per layer the median over the reps, then the mean over the 12
# layers, worst layer in brackets. Gate (PLAN-v3 §13 W2): G4 mean <= 1.0 ms/layer on text and random, every layer bit-exact.
# usage: analyze_w2.py RES_DIR > summary.md
import sys, re, os, glob
R = sys.argv[1]
def w2(path):
    by = {}
    ok = n = 0
    for l in open(path):
        if not l.startswith('LAYER'): continue
        d = dict(kv.split('=', 1) for kv in l.split()[2:] if '=' in kv)
        by.setdefault(int(d['G']), []).append(float(d['ms_med']))
        n += 1; ok += d['bytes_eq_cpu'] == '1' and d['bytes_eq_c3oracle'] == '1'
    return by, ok, n
def c3(path, variant):
    v = [float(re.search(r'total_med=(\S+)', l)[1]) for l in open(path) if 'variant=%s ' % variant in l]
    return v
print('# W2: HIP SPARSE_ATTN_PLAN on recaptured C3 rows, ub4096 d131k (generated by analyze_w2.py)\n')
print('| run | G4 mean [worst] ms/layer | G1 mean [worst] ms/layer | layers x G bit-exact (CPU op and C3 oracle) |')
print('|---|---|---|---|')
gate = True
for p in sorted(glob.glob(os.path.join(R, '*_p131072_*.out'))):
    name = os.path.basename(p)[:-4]
    if name.startswith(('opt', 'prof', 'c3plan')): continue
    by, ok, n = w2(p)
    cell = lambda G: '%.3f [%.3f]' % (sum(by[G]) / len(by[G]), max(by[G])) if G in by else '-'
    print('| %s | %s | %s | %d / %d |' % (name, cell(4), cell(1), ok, n))
    if ok != n: gate = False
    if 'shuf' not in name and 4 in by and sum(by[4]) / len(by[4]) > 1.0: gate = False
print('\nSame-run C3 harness (c3_plan, PR-verbatim rows kernel + C3 merges, hipEvent timing, `res/c3plan_*.out`):\n')
print('| rows | T0 (PR rows+merge) | P_asc_l512 (the merge W2 ports) |')
print('|---|---|---|')
for p in sorted(glob.glob(os.path.join(R, 'c3plan_*.out'))):
    t0, pa = c3(p, 'T0_pr_rows\\+merge'.replace('\\', '')), c3(p, 'P_asc_l512')
    f = lambda v: '%.3f [%.3f]' % (sum(v) / len(v), max(v)) if v else '-'
    print('| %s | %s | %s |' % (os.path.basename(p)[7:-4], f(t0), f(pa)))
print('\nGATE (G4 mean <= 1.0 ms on every unshuffled run, all bit-exact): %s' % ('PASS' if gate else 'FAIL'))
