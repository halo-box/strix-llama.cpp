#!/usr/bin/env python3
"""W12 done-when and AT-W12-BANDS analysis (PLAN-v3 §13 W12, §15, §16.5). Formulas are fixed here before the runs.

usage: analyze_w12.py LOGDIR EVDIR > w12_bands.md
  LOGDIR  logs of campaign.sh (TAG.log with QKLD_CHUNK lines, TAG.stats with QPIN_* lines)
  EVDIR   the evidence copy (EV = ~/dev/wt_lab/evidence/final219): round-1 logs for the reproduction checks

Per-chunk values: KLD = `QKLD_CHUNK <c> all=` (lo= / hi= for the Q11a split), agreement = `QPIN_QSA_CHUNK chunk=<c>`
overlap of the cb fire or of the first tk fire (tk1). Paired statistic of B - A: mean, SE = sd/sqrt(n) over chunks.
"""
import math, os, re, sys

L, EV = sys.argv[1], sys.argv[2]
B_4096, B_512, B_64 = 2.0e-4, 2.03e-4, 2.75e-4     # R1-Q8 d3, R1-UB d3 (PLAN-v3 §15 Q1)
SAT_Q8 = 9.387759e-05                             # R1-Q8 table B, eps 1e-7
Q4_FLOOR = 1.178e-4                               # smallest measured S_fast Q4 B_T (q8_0: 5.9e-5 + 3 x 1.96e-5, R1-E)
SELF_MAX = 3.7e-7                                 # uint16 base quantization (R1-UB noise)
BVK_OLD = 6.4e-4                                  # round-1 B_vk (R1-UB d4)
FAIL = []

def kld(path, field='all'):
    if not os.path.exists(path): return None
    d, s = {}, {}
    for line in open(path, errors='replace'):
        m = re.search(r'QKLD_CHUNK (\d+) all=(\S+) lo=(\S+) nlo=(\d+) hi=(\S+) nhi=(\d+)', line)
        if m:
            c = int(m.group(1)); v = {'all': m.group(2), 'lo': m.group(3), 'hi': m.group(5)}
            d[c] = float(v[field]); s[c] = v[field]
    return (d, s) if d else None

def agree(path):
    if not os.path.exists(path): return None
    raw = {}
    for line in open(path):
        m = re.match(r'QPIN_QSA_CHUNK chunk=(\d+) src=(\S+) n=(\d+) overlap=(\S+)', line)
        if m: raw.setdefault(int(m.group(1)), {})[m.group(2)] = m.group(4)
    out = {}
    for c, s in raw.items():
        v = s.get('cb', s.get('tk1'))
        if v is not None: out[c] = (float(v), v, 'cb' if 'cb' in s else 'tk')
    return out or None

def summary(tag):
    p = os.path.join(L, tag + '.log')
    if not os.path.exists(p): return None
    line = [x for x in open(p, errors='replace') if x.startswith('QPIN_SUMMARY')]
    return line[-1].strip() if line else None

def st(x):
    n = len(x); mu = sum(x) / n
    sd = math.sqrt(sum((v - mu) ** 2 for v in x) / (n - 1)) if n > 1 else 0.0
    return mu, sd / math.sqrt(n), n

def K(tag, field='all'):
    r = kld(os.path.join(L, tag + '.log'), field)
    return r[0] if r else None

def A(tag):
    r = agree(os.path.join(L, tag + '.stats'))
    return {c: v[0] for c, v in r.items()} if r else None

def paired(b, a):
    if b is None or a is None: return None
    ks = sorted(set(a) & set(b))
    if not ks: return None
    d = [b[k] - a[k] for k in ks]
    mu, se, n = st(d)
    return {'mean': mu, 'se': se, 'n': n, 'max': max(abs(x) for x in d), 'pos': sum(x > 0 for x in d), 'zero': all(x == 0 for x in d)}

def fmt(p):
    if p is None: return 'MISSING'
    return f"mean {p['mean']:+.6e}, SE {p['se']:.3e}, n {p['n']}, max|d| {p['max']:.3e}, >0 {p['pos']}/{p['n']}" + (' (bit-identical)' if p['zero'] else '')

def check(ok, what):
    print(f"- {'PASS' if ok else 'FAIL'}: {what}")
    if not ok: FAIL.append(what)

def arm_line(tag, field='all'):
    v = K(tag, field)
    if v is None: return f"| {tag} | MISSING | | |"
    mu, se, n = st([v[k] for k in sorted(v)])
    return f"| {tag} | {mu:.6e} | {se:.3e} | {n} |"

tags = sorted(f[:-4] for f in os.listdir(L) if f.endswith('.log'))
print('# W12 / AT-W12-BANDS results (W0-lab)\n')
print('Generated by `scripts/qsa-validation/w12/analyze_w12.py`; formulas fixed in the script before the runs.\n')
print('## Run health\n')
for t in tags:
    s = summary(t)
    if s is None: continue
    m = dict(re.findall(r'(\w+)=(-?\d+)', s))
    if m.get('mode') == '2':
        check(m.get('rows_absent') == '0' and m.get('moe_absent') == '0', f"{t}: rows_absent={m.get('rows_absent')} moe_absent={m.get('moe_absent')} rows_pin={m.get('rows_pin')} moe_pin={m.get('moe_pin')} cb={m.get('cb_tensors')} tk={m.get('tk_tensors')}")
    else:
        print(f"- record {t}: rows_rec={m.get('rows_rec')} moe_rec={m.get('moe_rec')} cb={m.get('cb_tensors')} tk={m.get('tk_tensors')}")

print('\n## Per-arm mean KLD (chunk SE)\n\n| arm | mean KLD | chunk SE | chunks |\n|---|---|---|---|')
for t in tags:
    if K(t) is not None: print(arm_line(t))

def hashes(tag, what):
    p = os.path.join(L, tag + '.log')
    if not os.path.exists(p): return None
    return {int(m.group(1)): m.group(2) for m in re.finditer(r'QKL_HASH ' + what + r' (\d+) (\S+) n=', open(p, errors='replace').read())} or None

print('\n## QPIN self-replay on every reference\n')
print('Gate: the replay is bit-identical to the reference (phase S: per-chunk QKL_HASH of the scored logits equal between the')
print('record and the self-replay), and phase S re-recorded the same reference the arms used (its self-replay QKLD_CHUNK')
print('values equal the campaign self-replay at %.9e). The plan states the self-replay as "KLD 0 (<= 3.7e-7)"; 3.7e-7 is the')
print('largest chunk R1-UB observed, not a bound of the uint16 base quantization, so it is reported, not gated.\n')
for ref, t, pre in (('ref8t0', 'a_f16_f16_u4096', 'c8192 x 8'), ('ref16t0', 'c_f16_f16_u4096', 'c8192 x 16'), ('ref32x8', 'd_f16_f16_u4096', 'c32768 x 8'),
                    ('vref8t0', 'v_f16_f16_u4096', 'Vulkan c8192 x 8'), ('ref8L', 'b_f16_f16_u4096', 'c8192 x 8 tail 8191'), ('ref2k', 'e_f16_f16_u2048', 'c2048 x 16')):
    v = K(t)
    if v is None: print(f"- {t}: not run"); FAIL.append(f'self {ref} missing'); continue
    mx = max(abs(x) for x in v.values())
    print(f"- {ref} ({pre}) {t}: max |chunk| {mx:.3e} ({'<=' if mx <= SELF_MAX else '>'} 3.7e-7), mean {st(list(v.values()))[0]:+.3e}")
    hb, hk = hashes(f's_{ref}_rec', 'base'), hashes(f's_{ref}_self', 'kld')
    if hb is None or hk is None: print(f"  - hash check: not run"); FAIL.append(f'hash {ref} missing'); continue
    check(hb == hk, f"{ref}: QKL_HASH record == self-replay in {sum(hb.get(c) == hk.get(c) for c in hb)}/{len(hb)} chunks (bit-identical replay)")
    a, b = kld(os.path.join(L, f's_{ref}_self.log')), kld(os.path.join(L, t + '.log'))
    check(a is not None and b is not None and a[1] == b[1], f"{ref}: phase-S self-replay QKLD_CHUNK == {t} at %.9e (same reference re-recorded)")
print('\nDirect-form bases: H3 (q4_0) is gating at 3.7e-7 like a reference; the other bases extend H3 and their self-check')
print('is reported, not gated: 3.7e-7 is the largest self-replay chunk observed in R1-UB, not a derived bound, and any bit')
print('change of the arm saturates near 1e-4 (R1-Q8), three orders above these values.\n')
for t in ('db_q4_0_q4_0_self', 'db_f16_f16_self', 'db_q8_0_q8_0_self', 'db_bf16_bf16_self', 'db_q8_0_f16_self', 'db_f16_q8_0_self'):
    v = K(t)
    if v is None: continue
    mx = max(abs(x) for x in v.values())
    if t == 'db_q4_0_q4_0_self': check(mx <= SELF_MAX, f"{t} (H3 base): max |chunk| {mx:.3e}")
    else: print(f"- INFO {t}: max |chunk| {mx:.3e} ({'<=' if mx <= SELF_MAX else '>'} 3.7e-7)")

def repro(tag, evlog, label):
    a = kld(os.path.join(L, tag + '.log')); b = kld(os.path.join(EV, evlog))
    if a is None or b is None: print(f"- {label}: MISSING ({tag} / {evlog})"); return
    ks = sorted(set(a[1]) | set(b[1]))
    eq = all(a[1].get(k) == b[1].get(k) for k in ks)
    mu, se, n = st([a[0][k] for k in sorted(a[0])])
    check(eq, f"{label}: {tag} per chunk == EV/{evlog} at %.9e ({sum(a[1].get(k) == b[1].get(k) for k in ks)}/{len(ks)} chunks equal); mean {mu:.6e} SE {se:.3e}")
    if not eq:
        print('  - new: ' + ' '.join(a[1].get(k, '-') for k in ks)); print('  - old: ' + ' '.join(b[1].get(k, '-') for k in ks))

print('\n## Control reproduction (P2-31)\n')
repro('a_q8_0_q8_0_u4096', 'r1ub/logs/h_q8_0_u4096.log', 'q8_0 ub4096 vs ref8t0 (R1-UB table D: 1.371668e-4, SE 1.25e-5)')
repro('a_f16_f16_u4096', 'r1ub/logs/h_f16_u4096.log', 'f16 self-replay vs ref8t0')
a = agree(os.path.join(L, 'c_q8_0_q8_0_u4096.stats')); b = agree(os.path.join(EV, 'r1e/r1e/logs/e_q8_idxq8.stats'))
if a and b:
    mu, se, n = st([a[k][0] for k in sorted(a)])
    eq = all(a[k][1] == b.get(k, (0, None))[1] for k in a) and set(a) == set(b)
    check(eq and f"{mu:.6f}" == "0.996743", f"agreement q8_0 ub4096 vs ref16t0: mean {mu:.6f} (R1-E 0.996743), SE {se:.2e}, per chunk == EV/r1e/r1e/logs/e_q8_idxq8.stats at %.9f: {eq}")
else:
    print('- agreement control: MISSING')
for t in ('f16', 'q8_0', 'q4_0'):
    repro(f'd_{t}_{t}_u4096', f'r1ub/logs/h32x8_{t}_u4096.log', f'c32768 x 8 {t} ub4096 vs ref32x8 (R1-UB table D)')

print('\n## H1: Q1-A bands for bf16 and the mixed pairs (c8192 x 8, ub2048 - ub4096, same route)\n')
print('B_T,4096 = max(mean + 3 SE of PR219(T) ub2048 - ub4096, B_4096 = 2.0e-4).\n')
print('| pair | route | ub2048 - ub4096 | mean + 3 SE | band B_T,4096 |\n|---|---|---|---|---|')
H1 = {}
for t in ('bf16_bf16', 'q8_0_f16', 'f16_q8_0'):
    for r, suf in (('default', ''), ('kind 1', '_sk1')):
        p = paired(K(f'a_{t}_u2048{suf}'), K(f'a_{t}_u4096{suf}'))
        if p is None: print(f"| {t} | {r} | MISSING | | |"); FAIL.append(f'H1 {t} {r} missing'); continue
        raw = p['mean'] + 3 * p['se']; band = max(raw, B_4096); H1[(t, r)] = band
        print(f"| {t} | {r} | {fmt(p)} | {raw:.3e} | **{band:.3e}** |")
p = paired(K('a_f16_f16_u2048'), K('a_f16_f16_u4096'))
print(f"\nf16 ub2048 - ub4096 under ref8t0 (context; R1-Q8 had +1.116e-4 under the default-trim ref8): {fmt(p)}")
check(all(v > 0 for v in H1.values()) and len(H1) == 6, 'every H1 band > 0 (floored)')

print('\n## Direct form (KLD against the clean same-type pinned output; H3 for q4_0, extended to every Q1-A type)\n')
print('band_direct(T) = max(ub2048 reorder, eps = 1e-7 saturation) + 3 x the chunk SE of the larger term; never 0.\n')
print('| type | ub2048 reorder (SE) | eps 1e-7 saturation (SE) | band_direct |\n|---|---|---|---|')
DIR = {}
for t, u2, d3 in tuple((x, f'db_{x}_u2048', f'db_{x}_d3e7') for x in ('f16_f16', 'q4_0_q4_0', 'q8_0_q8_0', 'bf16_bf16', 'q8_0_f16', 'f16_q8_0')):
    a2, a3 = K(u2), K(d3)
    if a2 is None or a3 is None: print(f"| {t} | MISSING | | |"); FAIL.append(f'direct {t} missing'); continue
    m2, s2, _ = st(list(a2.values())); m3, s3, _ = st(list(a3.values()))
    band = (m2 + 3 * s2) if m2 >= m3 else (m3 + 3 * s3); DIR[t] = band
    print(f"| {t} | {m2:.6e} ({s2:.2e}) | {m3:.6e} ({s3:.2e}) | **{band:.3e}** |")
if 'q4_0_q4_0' in DIR:
    m3 = st(list(K('db_q4_0_q4_0_d3e7').values()))[0]
    print(f"\nq4_0 saturation floor {m3:.6e} recorded next to q8_0's {SAT_Q8:.6e} (R1-Q8).")
check(all(v > 0 for v in DIR.values()) and len(DIR) == 6, 'every direct-form band > 0')

print('\n## H2: Q4 agreement bands (c8192 x 16, ref16t0, kind 1 partner)\n')
print('B_T = max(|mean shift kind-1 ub2048 - ub4096| + 3 SE, 1.178e-4); threshold_T = mean(PR219 kind 1 ub4096) - B_T.\n')
print('| pair | kind 1 ub4096 mean (SE) | ub2048 shift | B_T | threshold | kind 1 - tk |\n|---|---|---|---|---|---|')
H2 = {}
for t in ('bf16_bf16', 'q8_0_f16', 'f16_q8_0'):
    a4, a2, tk = A(f'c_{t}_u4096_sk1'), A(f'c_{t}_u2048_sk1'), A(f'c_{t}_u4096')
    if a4 is None or a2 is None: print(f"| {t} | MISSING | | | | |"); FAIL.append(f'H2 {t} missing'); continue
    m4, s4, n4 = st([a4[k] for k in sorted(a4)]); p = paired(a2, a4)
    bt = max(abs(p['mean']) + 3 * p['se'], Q4_FLOOR); H2[t] = (m4 - bt, bt)
    pk = paired(a4, tk)
    print(f"| {t} | {m4:.6f} ({s4:.2e}) | {fmt(p)} | {bt:.3e} | **{m4 - bt:.6f}** | {fmt(pk)} |")
check(len(H2) == 3 and all(b > 0 for _, b in H2.values()), 'every H2 B_T computed and > 0')

print('\n## H4: B_4096@32k (c32768 x 8, QKL_TAIL=4096, ub2048 - ub4096)\n')
H4 = {}
for t in ('f16', 'q8_0', 'q4_0'):
    p = paired(K(f'd_{t}_{t}_u2048'), K(f'd_{t}_{t}_u4096'))
    if p is None: print(f"- {t}: MISSING"); FAIL.append(f'H4 {t} missing'); continue
    H4[t] = p['mean'] + 3 * p['se']
    print(f"- {t}: {fmt(p)}; mean + 3 SE = {H4[t]:.3e}")
if len(H4) == 3:
    print(f"\n**B_4096@32k = {max(H4.values()):.3e}** (max over f16, q8_0, q4_0). Floor rule (§15): a type whose reorder is bit-identical takes B_4096@32k.")
    f2 = K('d_f16_f16_u2048')
    print(f"- C17 cross-check (f16 ub2048 floor, c32768 x 2: chunks 1.4e-4, 0.62e-4): chunks 0, 1 here = {f2.get(0, float('nan')):.3e}, {f2.get(1, float('nan')):.3e}")
check(len(H4) == 3 and max(H4.values()) > 0, 'B_4096@32k computed and > 0')

print('\n## V1/V2: Vulkan (W0-Vulkan reference vref8t0, c8192 x 8)\n')
i1, i2 = kld(os.path.join(L, 'v_old_f16_u4096_r1.log')), kld(os.path.join(L, 'v_old_f16_u4096_r2.log'))
if i1 and i2:
    check(i1[1] == i2[1], f"V2 (ii) == (i) per chunk at %.9e (determinism of the round-1 Vulkan tree)")
    mi, si, _ = st(list(i1[0].values()))
    invalid = mi >= BVK_OLD or abs(mi - BVK_OLD) <= 3 * si
    print(f"- V2 (i) master Vulkan delta (old PR219+#240 binary vs the W0-Vulkan reference): mean {mi:.6e}, SE {si:.3e}")
    print(f"- old vref8t0 reference {'INVALID (mean >= 6.4e-4 or within 3 SE of it): Q1-vk pairs new-Vulkan(T) with W0-Vulkan(T) only' if invalid else 'usable (mean below 6.4e-4 and not within 3 SE of it)'}")
else:
    print('- V2 (i)/(ii): MISSING'); FAIL.append('V2 i/ii missing')
p = paired(K('v_f16_f16_u2048'), K('v_f16_f16_u4096'))
if p:
    print(f"- V2 (iii) W0-Vulkan f16 ub2048 - ub4096: {fmt(p)}\n\n**B_vk = {p['mean'] + 3 * p['se']:.3e}** (mean + 3 SE)")
    check(p['mean'] + 3 * p['se'] > 0, 'B_vk > 0')
else:
    print('- V2 (iii): MISSING'); FAIL.append('V2 iii missing')
p = paired(K('v_f16_f16_u4096_nodq8'), K('v_f16_f16_u4096'))
print(f"- V2 (iv) GGML_VK_DENSE_DQ8=0 GGML_VK_HC_DQ8=0 vs default: {fmt(p)}")

print('\n## Q11a lo / hi split (U40; ref8L = c8192 x 8, QKL_TAIL=8191, QKL_SPLIT=2048; ub512 at -b 512 minus ub4096)\n')
LO = {}
print('| pair | region | ub512 - ub4096 | mean + 3 SE |\n|---|---|---|---|')
for t in ('f16_f16', 'q8_0_q8_0', 'q4_0_q4_0', 'bf16_bf16', 'q8_0_f16', 'f16_q8_0'):
    for reg in ('lo', 'hi', 'all'):
        p = paired(K(f'b_{t}_u512', reg), K(f'b_{t}_u4096', reg))
        if p is None: print(f"| {t} | {reg} | MISSING | |"); continue
        LO.setdefault(reg, {})[t] = p['mean'] + 3 * p['se']
        print(f"| {t} | {reg} | {fmt(p)} | {p['mean'] + 3 * p['se']:.3e} |")
if 'lo' in LO and len(LO['lo']) == 6:
    print(f"\n**B_512,lo = max(max over pairs {max(LO['lo'].values()):.3e}, B_512 = 2.03e-4) = {max(max(LO['lo'].values()), B_512):.3e}**; hi max {max(LO['hi'].values()):.3e} (cross-check of B_512 on another reference)")
else:
    FAIL.append('Q11a split incomplete')

print('\n## Q11b shift (ref2k = c2048 x 16, dense f16 b/ub 2048 reference, MoE pins)\n')
QB = {}
for t in ('f16_f16', 'q8_0_q8_0', 'q4_0_q4_0', 'bf16_bf16', 'q8_0_f16', 'f16_q8_0'):
    p = paired(K(f'e_{t}_u512'), K(f'e_{t}_u2048'))
    if p is None: print(f"- {t}: MISSING"); continue
    QB[t] = max(p['mean'] + 3 * p['se'], B_512)
    print(f"- {t} ub512 - ub2048: {fmt(p)}; Q11b band max(mean + 3 SE, B_512) = **{QB[t]:.3e}**")
for t in ('f16', 'q8_0'):
    p = paired(K(f'e_{t}_{t}_u16'), K(f'e_{t}_{t}_u2048'))
    print(f"- {t} ub16 - ub2048 (context for the ub16 arms): {fmt(p)}")
if len(QB) != 6: FAIL.append('Q11b incomplete')

print('\n## Verdict\n')
print('AT-W12-BANDS: ' + ('PASS' if not FAIL else 'FAIL / INCOMPLETE: ' + '; '.join(FAIL)))
sys.exit(1 if FAIL else 0)
